//! Instruction metadata boundary.

/// Stable identifier used by CPU steps and trace output.
#[derive(Clone, Copy, Debug, Eq, PartialEq)]
pub enum InstructionId {
    AdcAbsolute,
    AdcDirect,
    AdcImmediate,
    AndImmediate,
    AslAccumulator,
    Bcc,
    Bcs,
    Beq,
    Bmi,
    Bne,
    Bpl,
    Bra,
    Bvc,
    Bvs,
    Brk,
    CLC,
    CLD,
    CLI,
    CLV,
    CmpImmediate,
    DecAccumulator,
    Dex,
    Dey,
    EorImmediate,
    IncAccumulator,
    Inx,
    Iny,
    JML,
    JMP,
    Jsl,
    Jsr,
    LdaAbsolute,
    LdaDirect,
    LdaLong,
    LdaImmediate,
    LdxImmediate,
    LdyImmediate,
    Nop,
    OraImmediate,
    Pha,
    Phx,
    Phy,
    Php,
    Pla,
    Plp,
    Plx,
    Ply,
    Rep,
    Rti,
    Rtl,
    Rts,
    SBCImmediate,
    SEC,
    SED,
    SEI,
    Sep,
    StaDirect,
    StaAbsolute,
    StaLong,
    StzAbsolute,
    Stp,
    Tcd,
    Tcs,
    Tax,
    Tay,
    Tdc,
    Tsc,
    Txa,
    Tya,
    Tsx,
    Txs,
    Wai,
    Xba,
    Xce,
    Unknown(u8),
    Placeholder,
}

impl InstructionId {
    pub const fn from_opcode(opcode: u8) -> Self {
        match opcode {
            0x09 => Self::OraImmediate,
            0x0a => Self::AslAccumulator,
            0x10 => Self::Bpl,
            0x00 => Self::Brk,
            0x18 => Self::CLC,
            0x20 => Self::Jsr,
            0x22 => Self::Jsl,
            0x24 => Self::Unknown(opcode),
            0x28 => Self::Plp,
            0x29 => Self::AndImmediate,
            0x30 => Self::Bmi,
            0x38 => Self::SEC,
            0x40 => Self::Rti,
            0x4c => Self::JMP,
            0x5c => Self::JML,
            0x60 => Self::Rts,
            0x62 => Self::Unknown(opcode),
            0x69 => Self::AdcImmediate,
            0x6b => Self::Rtl,
            0x70 => Self::Bvs,
            0x78 => Self::SEI,
            0x80 => Self::Bra,
            0x82 => Self::Unknown(opcode),
            0x88 => Self::Dey,
            0x8a => Self::Txa,
            0x8b => Self::Unknown(opcode),
            0x8d => Self::StaAbsolute,
            0x8f => Self::StaLong,
            0x90 => Self::Bcc,
            0x98 => Self::Tya,
            0x9a => Self::Txs,
            0xa0 => Self::LdyImmediate,
            0xa2 => Self::LdxImmediate,
            0xa8 => Self::Tay,
            0xa9 => Self::LdaImmediate,
            0xaa => Self::Tax,
            0xb0 => Self::Bcs,
            0xb8 => Self::CLV,
            0xc0 => Self::CmpImmediate,
            0xc2 => Self::Rep,
            0xc8 => Self::Iny,
            0xca => Self::Dex,
            0xd0 => Self::Bne,
            0xd8 => Self::CLD,
            0xe0 => Self::CmpImmediate,
            0xe2 => Self::Sep,
            0xe8 => Self::Inx,
            0xe9 => Self::SBCImmediate,
            0xea => Self::Nop,
            0xeb => Self::Xba,
            0xf0 => Self::Beq,
            0xf8 => Self::SED,
            0xfb => Self::Xce,
            opcode => Self::Unknown(opcode),
        }
    }
}
